#!/usr/bin/env python3
"""Keep a project's DESIGN.md READ ORDER whole, and its table of contents in the project's own rules dir.

THE READ ORDER (rule 26-canonical-design): every DESIGN.md opens with it — its first `##` heading is `## READ ORDER` —
naming what the level is, which child design and which procedure to read for which work, and, on its line
`ARCHIVE AND PROGRAM FOLDERS:`, the folders whose files are evidence, generated output or a program's source. It names
every child DESIGN.md beneath it — the nearest DESIGN.md down each folder, outside those folders — and every DESIGN.md
it names resolves.

THE TOC (rule design-docs-keep-a-toc): it lives at `<project>/.claude/rules/design_toc.md`, a hand-written top (the
"where the current answer is" table) and a generated block between TOC markers. This script writes only the generated
block, from DESIGN.md's `##` and `###` headings (headings inside code fences are skipped), each with its line number.

    python3 design_toc.py <project_dir>           # rewrite the TOC block
    python3 design_toc.py <project_dir> --check   # the READ ORDER checked, and the TOC where the project keeps one:
                                                  # exit 1 naming each finding, 0 when both hold
    python3 design_toc.py <project_dir> --init    # create the TOC rule if it does not exist, then write

THE STATE (rule 26-canonical-design): a design states the intended final state and the steps by which it evolves, and
where anything stands lives only in the project's boards. A design found holding state has each passage of it fenced
where it stands, between the fence's opening line `> **WARNING: STATE MENTIONED IN DESIGN.MD -- …**` and its closing
line `> **END OF STATE FENCE**`. `--check` admits every line from an opening line to its closing line, and names how
many lines the fences hold that are still to be moved into the boards; it refuses a state mark — `ASPIRATIONAL`, an
`as built` statement, a `✅ MEASURED` or `⏳ AS OF` claim — outside every fence, naming each line, and an opening
line with no closing line after it. Lines inside a code fence are not read for it.

<project_dir> defaults to the current directory. A project with no TOC rule is checked for its READ ORDER alone.
"""
import os
import re
import subprocess
import sys

BEGIN = "<!-- TOC:BEGIN (generated by design_toc.py; do not hand-edit) -->"
END = "<!-- TOC:END -->"
GLYPHS = re.compile(r"[⭐⛔⚠✅⏸️]+")
MAXLEN = 120
READ_ORDER = "READ ORDER"
ARCHIVE_LINE = "ARCHIVE AND PROGRAM FOLDERS:"
_TICKS = re.compile(r"`([^`\n]+)`")
_NAMED = re.compile(r"[\w./~@+-]*DESIGN\.md")
FENCE_OPEN = ("> **WARNING: STATE MENTIONED IN DESIGN.MD -- NOT ALLOWED IN DESIGN. THIS MUST MOVE TO STATE FILE WHEN "
              "WORKED ON. DO NOT REMOVE THIS FENCE UNTIL THE STATE IS RECONCILED AND EVERY INTENDED THING IS BUILT AS "
              "INTENDED. DO NOT SKIP THIS.**")
FENCE_CLOSE = "> **END OF STATE FENCE**"
STATE_MARK = re.compile(r"ASPIRATIONAL|\bAS BUILT\b|\b[Aa]s built\b|✅ MEASURED|⏳ AS OF")

SKELETON = """# DESIGN.md — THE TABLE OF CONTENTS (and where each current answer lives)

<docsys kind="index" role="instance"/>

TRIGGER:[about to write, draft or decide anything this project's DESIGN.md governs · about to
answer "did we already decide X?" · any edit to DESIGN.md]
DO:[find the question in WHERE THE CURRENT ANSWER IS, then jump with `Read(offset=<line>)` · if it
is not in the table, scan the TOC headings before concluding it was never decided · regenerate
after ANY DESIGN.md edit, same commit · add a row when a question gets asked twice]
NOT:[answer from memory of the conversation · hand-edit the generated block]

## WHERE THE CURRENT ANSWER IS

| question | go to | careful |
|---|---|---|

## THE TOC — generated from DESIGN.md's headings; `L` = the line to `Read(offset=…)` from

{BEGIN}
{END}
"""


def clean(text):
    text = GLYPHS.sub("", text).replace("**", "").replace("*", "")
    text = re.sub(r"\s+", " ", text).strip(" -—")
    return text if len(text) <= MAXLEN else text[: MAXLEN - 1].rstrip() + "…"


def build(design):
    lines = open(design, encoding="utf-8").read().split("\n")
    out, fenced = [], False
    for n, line in enumerate(lines, 1):
        if line.lstrip().startswith("```"):
            fenced = not fenced
            continue
        if fenced:
            continue
        if line.startswith("## "):
            out.append(f"- `L{n}` **{clean(line[3:])}**")
        elif line.startswith("### "):
            out.append(f"  - `L{n}` {clean(line[4:])}")
    secs = sum(1 for o in out if o.startswith("- "))
    subs = sum(1 for o in out if o.startswith("  - "))
    head = f"DESIGN.md: {len(lines)} lines · {secs} sections · {subs} subsections"
    return "\n".join([BEGIN, head, ""] + out + [END])


# ── the READ ORDER ──────────────────────────────────────────────────────────────────────────────────────────────────

def read_order_section(text):
    """(the READ ORDER section's text, or None; the title of the first `##` heading) — headings in fences skipped."""
    lines, fenced, start, first = text.split("\n"), False, None, None
    for i, line in enumerate(lines):
        if line.lstrip().startswith("```"):
            fenced = not fenced
            continue
        if fenced or not line.startswith("## "):
            continue
        if start is None and first is None:
            first = line[3:].strip()
            if first.strip("*").upper().startswith(READ_ORDER):
                start = i
            continue
        if start is not None:
            return "\n".join(lines[start:i]), first
    return ("\n".join(lines[start:]) if start is not None else None), first


def archive_folders(section):
    """The folders the line `ARCHIVE AND PROGRAM FOLDERS:` names, relative to the design; None when there is no line."""
    for line in section.split("\n"):
        head = line.replace(f"`{ARCHIVE_LINE}`", ARCHIVE_LINE).replace(f"**{ARCHIVE_LINE}**", ARCHIVE_LINE)
        head = head.strip().lstrip("-*· ")
        if head.startswith(ARCHIVE_LINE):
            rest = head[len(ARCHIVE_LINE):]
            names = [t.strip() for t in _TICKS.findall(rest)] or [t for t in re.split(r"[\s·,]+", rest) if t]
            return [n.rstrip("/") for n in names if n.strip("`").lower() not in ("none", "—", "-", "")]
    return None


def designs_on_disk(project):
    """Every DESIGN.md beneath the project, relative to it: the files git tracks or would track, or every one on disk
    outside a dot-folder where the project is in no git checkout."""
    r = subprocess.run(["git", "-C", project, "ls-files", "-z", "--cached", "--others", "--exclude-standard", "--", "."],
                       capture_output=True, text=True)
    if r.returncode == 0:
        found = [p for p in r.stdout.split("\0") if p.endswith("DESIGN.md") and os.path.basename(p) == "DESIGN.md"]
    else:
        found = []
        for dp, dns, fns in os.walk(project):
            dns[:] = [d for d in dns if not d.startswith(".")]
            if "DESIGN.md" in fns:
                found.append(os.path.relpath(os.path.join(dp, "DESIGN.md"), project))
    out = []
    for p in found:
        p = os.path.normpath(p).replace(os.sep, "/")
        if p == "DESIGN.md" or any(part.startswith(".") for part in p.split("/")[:-1]):
            continue
        if os.path.isfile(os.path.join(project, p)):
            out.append(p)
    return sorted(set(out))


def children(project, exempt):
    """The nearest DESIGN.md down each folder, outside the exempt folders."""
    inside = lambda p, d: p == d or p.startswith(d + "/")
    kept = [p for p in designs_on_disk(project) if not any(inside(p, e) for e in exempt)]
    dirs = [os.path.dirname(p) for p in kept]
    return [p for p in kept if not any(d and d != os.path.dirname(p) and inside(os.path.dirname(p), d) for d in dirs)]


def check_read_order(project):
    """Every finding about the DESIGN.md's READ ORDER, and the children it was checked against."""
    design = os.path.join(project, "DESIGN.md")
    text = open(design, encoding="utf-8").read()
    section, first = read_order_section(text)
    if section is None:
        where = f"its first `##` heading is `{first}`" if first else "it has no `##` heading"
        return [f"no READ ORDER at its head — {where}; open it with `## READ ORDER` (rule 26-canonical-design)"], []
    findings = []
    names = archive_folders(section)
    if names is None:
        findings.append(f"its READ ORDER has no `{ARCHIVE_LINE}` line — name the folders the checks skip, or `none`")
        names = []
    exempt = [os.path.normpath(n).replace(os.sep, "/") for n in names]
    for n in exempt:
        if not os.path.isdir(os.path.join(project, n)):
            findings.append(f"its `{ARCHIVE_LINE}` line names `{n}/`, which is not a folder beneath it")
    kids = children(project, exempt)
    for kid in kids:
        if kid not in section:
            findings.append(f"its READ ORDER does not name the child design `{kid}` — add the work it is read for")
    for named in sorted(set(_NAMED.findall(section))):
        if named == "DESIGN.md":
            continue
        p = os.path.expanduser(named) if named.startswith("~") else named
        p = p if os.path.isabs(p) else os.path.join(project, p)
        if not os.path.isfile(p):
            findings.append(f"its READ ORDER names `{named}`, which is gone — remove it or name where it is now")
    return findings, kids


def check_state(text):
    """(each line outside every state fence holding a state mark, as `L<n>: <text>`; the fenced lines that are not
    blank; the line number of a fence's opening line with no closing line after it, or None)."""
    outside, inside, opened, code = [], 0, None, False
    for n, line in enumerate(text.split("\n"), 1):
        if line.lstrip().startswith("```"):
            code = not code
            continue
        if code:
            continue
        if opened is None and line.strip() == FENCE_OPEN:
            opened = n
        elif opened is not None and line.strip() == FENCE_CLOSE:
            opened = None
        elif opened is not None:
            inside += 1 if line.strip() else 0
        elif STATE_MARK.search(line):
            outside.append(f"L{n}: {line.strip()[:120]}")
    return outside, inside, opened


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    project = os.path.abspath(args[0] if args else os.getcwd())
    design = os.path.join(project, "DESIGN.md")
    rule = os.path.join(project, ".claude", "rules", "design_toc.md")
    if not os.path.isfile(design):
        print(f"design_toc: no DESIGN.md at {design} — nothing done", file=sys.stderr)
        return 2
    if "--check" in sys.argv:
        findings, kids = check_read_order(project)
        outside, inside, opened = check_state(open(design, encoding="utf-8").read())
        for line in outside:
            findings.append(f"it holds a current state outside every state fence — fence the passage where it stands, "
                            f"then move it into the boards (rule 26-canonical-design): {line}")
        if opened is not None:
            findings.append(f"its state fence opened at L{opened} has no `{FENCE_CLOSE}` after it — close the fence "
                            f"where its passage ends (rule 26-canonical-design)")
        toc = "no TOC rule: checked for its READ ORDER alone"
        if os.path.isfile(rule):
            text = open(rule, encoding="utf-8").read()
            if BEGIN not in text or END not in text:
                findings.append(f"TOC markers missing in {rule}")
            else:
                inner = text.split(BEGIN, 1)[1].split(END, 1)[0]
                if BEGIN + inner + END != build(design):
                    findings.append(f"the TOC is STALE — regenerate: python3 {os.path.abspath(__file__)} {project}")
                else:
                    toc = f"the TOC CURRENT at {rule}"
        if findings:
            print(f"design_toc: REFUSED — {design}, {len(findings)} finding(s):")
            for f in findings:
                print(f"  ✘ {f}")
            return 1
        owed = f"; its state fences hold {inside} line(s) of state to move into the boards" if inside else ""
        print(f"design_toc: CURRENT — {design}: its READ ORDER names its {len(kids)} child design(s); {toc}{owed}")
        return 0
    if not os.path.isfile(rule):
        if "--init" not in sys.argv:
            print(f"design_toc: no rule at {rule} — run with --init to create it", file=sys.stderr)
            return 2
        os.makedirs(os.path.dirname(rule), exist_ok=True)
        open(rule, "w", encoding="utf-8").write(SKELETON.format(BEGIN=BEGIN, END=END))
        print(f"design_toc: created {rule}")
    text = open(rule, encoding="utf-8").read()
    if BEGIN not in text or END not in text:
        print(f"design_toc: TOC markers missing in {rule} — nothing written", file=sys.stderr)
        return 2
    before, rest = text.split(BEGIN, 1)
    _inner, after = rest.split(END, 1)
    fresh = build(design)
    open(rule, "w", encoding="utf-8").write(before + fresh + after)
    print(f"design_toc: written — {fresh.splitlines()[1]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
